fn readme(package_name: &str) -> String {
    format!(
        r#"# {package_name}

Generated by `rustui`.

## Interface Policy

- Quit is command-mode only: `:q`, `:quit`, `:exit`, or `:q!`.
- `Esc` cancels transient UI state. It never quits.
- `q` is available for local behavior, but it is not a global quit key.
- `Ctrl-C` is not bound to quit by default.
- `:` opens command mode from any pane.
- `?` opens help.
- `Tab` and `Shift-Tab` move focus.

The scaffold is intentionally editable. Start with `src/app.rs` for local
behavior, `src/tui/keymap.rs` for key policy, and `src/tui/theme.rs` for color
themes. `src/tui/style.rs` holds design tokens, selectors, and the style-rule
DSL for per-element styling. Tokio is part of the scaffold so blocking work can
be moved into background tasks without freezing the TUI scene.

## Non-Blocking Work

The TUI runtime is async. Use `tokio::spawn` for long-running work and send
results back through the app-owned task channel. `App::poll_tasks()` is called
from the render loop and is the standard place to fold task results back into
scene state.
"#
    )
}

