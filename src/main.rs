const RATATUI_VERSION: &str = "0.30.1";
const CROSSTERM_VERSION: &str = "0.29.0";
const COLOR_EYRE_VERSION: &str = "0.6.5";
const TOKIO_VERSION: &str = "1";

fn main() {
    if let Err(error) = run(env::args().skip(1).collect()) {
        eprintln!("error: {error}");
        process::exit(1);
    }
}

fn run(args: Vec<String>) -> Result<(), String> {
    match args.as_slice() {
        [] => Err(usage()),
        [command] if command == "--help" || command == "-h" => {
            println!("{}", usage());
            Ok(())
        }
        [command, project_name] if command == "init" => init(project_name),
        [command, ..] if command == "init" => Err(
            "rustui init currently accepts only a project name; options are reserved for later"
                .to_string(),
        ),
        [command, ..] => Err(format!("unknown command `{command}`\n\n{}", usage())),
    }
}

fn usage() -> String {
    "usage:\n  rustui init <project_name>\n\nexample:\n  rustui init my-tui".to_string()
}

fn init(project_name: &str) -> Result<(), String> {
    let target = PathBuf::from(project_name);
    let package_name = package_name_for(&target)?;

    ensure_target_is_writable(&target)
        .map_err(|error| format!("cannot initialize `{}`: {error}", target.to_string_lossy()))?;

    let files = project_files(&package_name);
    for (relative_path, contents) in files {
        write_file(&target.join(relative_path), contents).map_err(|error| {
            format!(
                "failed to write `{}`: {error}",
                target.join(relative_path).to_string_lossy()
            )
        })?;
    }

    println!("created `{}`", target.to_string_lossy());
    println!("next:");
    println!("  cd {}", target.to_string_lossy());
    println!("  cargo run");

    Ok(())
}

fn package_name_for(target: &Path) -> Result<String, String> {
    let Some(name) = target.file_name().and_then(|name| name.to_str()) else {
        return Err("project name cannot be empty".to_string());
    };

    if !is_valid_package_name(name) {
        return Err(
            "project name must start with an ASCII letter and contain only letters, numbers, `_`, or `-`"
                .to_string(),
        );
    }

    Ok(name.to_string())
}

fn is_valid_package_name(name: &str) -> bool {
    let mut chars = name.chars();
    let Some(first) = chars.next() else {
        return false;
    };

    first.is_ascii_alphabetic()
        && chars.all(|character| {
            character.is_ascii_alphanumeric() || character == '_' || character == '-'
        })
}

fn ensure_target_is_writable(target: &Path) -> io::Result<()> {
    if target.exists() {
        if target.read_dir()?.next().is_some() {
            return Err(io::Error::new(
                io::ErrorKind::AlreadyExists,
                "target directory already exists and is not empty",
            ));
        }
    } else {
        fs::create_dir_all(target)?;
    }

    fs::create_dir_all(target.join("src/tui"))?;
    Ok(())
}

fn write_file(path: &Path, contents: String) -> io::Result<()> {
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent)?;
    }

    fs::write(path, contents)
}

